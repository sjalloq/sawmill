"""The ``sawmill rules`` command group: list, find unused and generate rules."""

from __future__ import annotations

import datetime
from pathlib import Path

import rich_click as click

from sawmill.cli.check import unused_rules
from sawmill.cli.common import (
    SawmillCliError,
    emit_warnings,
    manifest_options,
    run_selected,
    select_targets,
)
from sawmill.core.plugin import get_plugin_manager
from sawmill.core.rules import RuleValidationError
from sawmill.core.runner import RunnerError, TargetResult, load_rule_files_for
from sawmill.models.message import Message
from sawmill.models.rule import Rule
from sawmill.utils.author import discover_author
from sawmill.utils.toml import escape_toml_basic_string

TODO_COMMENT = "TODO: explain why this is acceptable"
_FIRST_CONTENT_MAX = 80


def rule_list_line(rule: Rule) -> str:
    """Return the ``rules list`` line for one rule."""
    keys = []
    for key, value in rule.match_keys().items():
        shown = f"[{','.join(value)}]" if isinstance(value, list) else value
        keys.append(f"{key}={shown}")
    parts = [rule.display, " ".join(keys)]
    if rule.max_count is not None:
        parts.append(f"max_count={rule.max_count}/{rule.per}")
    parts.append(f"# {rule.comment}")
    return "  ".join(parts)


def rule_unused_line(rule: Rule) -> str:
    """Return the ``rules unused`` line for one rule."""
    source = str(rule.source.resolve()) if rule.source is not None else ""
    return f"{rule.display}  {source}:{rule.line}  # {rule.comment}"


def _first_content(message: Message) -> str:
    text = " ".join(message.content.split())
    return text[:_FIRST_CONTENT_MAX]


def generate_rule_file(result: TargetResult, min_level: int, author: str, today: str) -> str:
    """Return a rule file waiving every unwaived message at or above ``min_level``.

    Messages without an id, or with no or unknown severity, are skipped.
    Rules are sorted by severity level descending, count descending, then id.
    """
    level_map = {s.id.lower(): s.level for s in result.severity_levels}
    found: dict[str, tuple[int, int, Message]] = {}
    for log in result.logs:
        for msg in log.unwaived:
            if msg.message_id is None or msg.severity is None:
                continue
            level = level_map.get(msg.severity.lower())
            if level is None or level < min_level:
                continue
            prev = found.get(msg.message_id)
            if prev is None:
                found[msg.message_id] = (level, 1, msg)
            else:
                found[msg.message_id] = (max(prev[0], level), prev[1] + 1, prev[2])
    ordered = sorted(found.items(), key=lambda kv: (-kv[1][0], -kv[1][1], kv[0]))

    esc = escape_toml_basic_string
    lines = [
        f"# Generated by sawmill rules generate for {result.qualified_name} on {today}",
        "# Review every rule and replace the comment before committing.",
        "",
        "[rules]",
        f'plugin = "{esc(result.plugin_name)}"',
    ]
    for mid, (_, count, first) in ordered:
        lines.append("")
        lines.append(f"[[rule]]  # {count} matches, first: {_first_content(first)}")
        lines.append(f'id = "{esc(mid)}"')
        lines.append(f'comment = "{esc(TODO_COMMENT)}"')
        if author:
            lines.append(f'author = "{esc(author)}"')
        lines.append(f'date = "{esc(today)}"')
    return "\n".join(lines) + "\n"


@click.group()
def rules() -> None:
    """List, audit and generate rules."""


@rules.command("list")
@click.argument("names", metavar="[TARGET...]", nargs=-1)
@click.option("--all", "all_targets", is_flag=True, help="Select every target of every manifest.")
@manifest_options
def list_rules(
    names: tuple[str, ...],
    all_targets: bool,
    manifest_path: Path | None,
    roots: tuple[Path, ...],
) -> None:
    """List the rules in scope for each target, in matching order."""
    refs = select_targets(manifest_path, roots, names, all_targets)
    out: list[str] = []
    for ref in refs:
        try:
            files = load_rule_files_for(ref)
        except (RunnerError, RuleValidationError) as e:
            raise SawmillCliError(str(e)) from e
        out.append(f"== {ref.manifest.name}:{ref.target.name}")
        out.extend(rule_list_line(rule) for rf in files for rule in rf.rules)
    for line in out:
        click.echo(line)


@rules.command("unused")
@click.argument("names", metavar="[TARGET...]", nargs=-1)
@click.option("--all", "all_targets", is_flag=True, help="Run every target of every manifest.")
@manifest_options
def unused(
    names: tuple[str, ...],
    all_targets: bool,
    manifest_path: Path | None,
    roots: tuple[Path, ...],
) -> None:
    """Run targets and list rules that matched nothing across the run."""
    results = run_selected(
        manifest_path, roots, names, all_targets, None, manager=get_plugin_manager()
    )
    emit_warnings(results)
    found = unused_rules(results)
    if not found:
        click.echo("No unused rules.")
        return
    for rule in found:
        click.echo(rule_unused_line(rule))


@rules.command("generate")
@click.argument("names", metavar="TARGET", nargs=-1)
@click.option(
    "--min-level",
    "min_level",
    type=int,
    default=1,
    show_default=True,
    metavar="N",
    help="Only generate rules for messages at or above severity level N.",
)
@manifest_options
def generate(
    names: tuple[str, ...],
    min_level: int,
    manifest_path: Path | None,
    roots: tuple[Path, ...],
) -> None:
    """Run TARGET and print a rule file waiving its unwaived messages."""
    if len(names) != 1:
        raise SawmillCliError("rules generate takes exactly one TARGET")
    results = run_selected(manifest_path, roots, names, False, None, manager=get_plugin_manager())
    if len(results) != 1:
        raise SawmillCliError(f"'{names[0]}' selected {len(results)} targets; expected one")
    emit_warnings(results)
    result = results[0]
    max_level = max((s.level for s in result.severity_levels), default=0)
    if not 0 <= min_level <= max_level:
        levels = ", ".join(
            f"{s.id}={s.level}" for s in sorted(result.severity_levels, key=lambda s: -s.level)
        )
        raise SawmillCliError(f"--min-level {min_level} out of range 0..{max_level}; {levels}")
    today = datetime.date.today().isoformat()
    click.echo(generate_rule_file(result, min_level, discover_author(), today), nl=False)
